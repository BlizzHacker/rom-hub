"""A fake self-hosted shop for testing search and the download handoff.

Standard library only. It binds 127.0.0.1 and serves:

- `/api/remote/sections`, a CyberFoil sections response listing every file
- `/`, a Tinfoil JSON index whose one nested `directories` entry is `/more`
- `/api/download/<token>`, an Ownfoil-style download route
- on a second port, `/files/<token>`, which `/api/download/mirror`
  redirects to with a 302, so a redirect to a second origin can be tested

With `--user` and `--password`, every route on the first port requires
HTTP Basic auth. The second port never does, since a download client drops
credentials when a redirect changes origin.

The files are a few kilobytes of generated bytes under made-up names and
title IDs. They contain no game data.

    python3 tools/fixture_shop.py --port 8465 --mirror-port 8466 \\
        --user fixture-user --password fixture
"""

import argparse
import base64
import json
import threading
from dataclasses import dataclass
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import quote

HOST = "127.0.0.1"


@dataclass(frozen=True)
class FixtureFile:
    token: str
    filename: str
    section: str

    @property
    def body(self) -> bytes:
        seed = f"switchfoil fixture file {self.filename}\n".encode()
        return (seed * (4096 // len(seed) + 1))[:4096]


FILES = (
    FixtureFile("base", "Fixture Game [0100F1C700000000][v0].nsp", "base"),
    FixtureFile("update", "Fixture Game [0100F1C700000800][v65536].nsp", "updates"),
    FixtureFile("dlc", "Fixture Game Bonus Pack [0100F1C700001001][v0].nsp", "dlc"),
    FixtureFile("mirror", "Fixture Game [0100F1C700000000][v0].nsz", "base"),
)
BY_TOKEN = {f.token: f for f in FILES}


def download_path(file: FixtureFile) -> str:
    return f"/api/download/{file.token}#{quote(file.filename)}"


def _entry(file: FixtureFile) -> dict:
    return {"url": download_path(file), "size": len(file.body)}


def sections_body() -> dict:
    sections = []
    for section in ("base", "updates", "dlc"):
        items = [_entry(f) for f in FILES if f.section == section]
        sections.append({"id": section, "title": section.title(), "items": items})
    return {"success": "switchfoil fixture shop", "sections": sections}


def index_body() -> dict:
    return {
        "success": "switchfoil fixture shop",
        "files": [_entry(BY_TOKEN["base"])],
        "directories": ["/more"],
    }


def more_body() -> dict:
    return {"files": [_entry(f) for f in FILES if f.token != "base"]}


class FixtureServer(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, port, handler, user=None, password=None):
        super().__init__((HOST, port), handler)
        self.user = user
        self.password = password
        self.mirror_origin = ""
        self.requests: list[tuple[str, dict[str, str]]] = []
        self.lock = threading.Lock()

    @property
    def origin(self) -> str:
        return f"http://{HOST}:{self.server_port}"

    def record(self, path, headers):
        with self.lock:
            self.requests.append((path, dict(headers.items())))


class _Handler(BaseHTTPRequestHandler):
    server: FixtureServer

    def log_message(self, format, *args):
        pass

    def _send(self, status, body=b"", content_type="application/json", headers=None):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        for name, value in (headers or {}).items():
            self.send_header(name, value)
        self.end_headers()
        self.wfile.write(body)

    def _json(self, data, status=200):
        self._send(status, json.dumps(data).encode())


class ShopHandler(_Handler):
    def _authorised(self) -> bool:
        if not self.server.user:
            return True
        raw = f"{self.server.user}:{self.server.password}".encode()
        expected = "Basic " + base64.b64encode(raw).decode()
        return self.headers.get("Authorization") == expected

    def do_GET(self):
        self.server.record(self.path, self.headers)
        path = self.path.split("?")[0]
        if not self._authorised():
            body = json.dumps({"error": "Shop requires authentication."}).encode()
            self._send(401, body, headers={"WWW-Authenticate": 'Basic realm="fixture"'})
            return
        if path == "/":
            self._json(index_body())
        elif path == "/more":
            self._json(more_body())
        elif path == "/api/remote/sections":
            self._json(sections_body())
        elif path == "/api/download/mirror" and self.server.mirror_origin:
            self._send(302, headers={"Location": f"{self.server.mirror_origin}/files/mirror"})
        elif path.startswith("/api/download/") and path.rpartition("/")[2] in BY_TOKEN:
            body = BY_TOKEN[path.rpartition("/")[2]].body
            self._send(200, body, "application/octet-stream")
        else:
            self._json({"error": "not found"}, 404)


class MirrorHandler(_Handler):
    def do_GET(self):
        self.server.record(self.path, self.headers)
        token = self.path.split("?")[0].rpartition("/")[2]
        if self.path.startswith("/files/") and token in BY_TOKEN:
            self._send(200, BY_TOKEN[token].body, "application/octet-stream")
        else:
            self._json({"error": "not found"}, 404)


def start(port=0, mirror_port=0, user=None, password=None):
    """Start the shop and its mirror on threads. Port 0 picks a free port."""
    shop = FixtureServer(port, ShopHandler, user, password)
    mirror = FixtureServer(mirror_port, MirrorHandler)
    shop.mirror_origin = mirror.origin
    for server in (shop, mirror):
        threading.Thread(target=server.serve_forever, daemon=True).start()
    return shop, mirror


def stop(*servers):
    for server in servers:
        server.shutdown()
        server.server_close()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--mirror-port", type=int, required=True)
    parser.add_argument("--user")
    parser.add_argument("--password")
    args = parser.parse_args(argv)
    if bool(args.user) != bool(args.password):
        parser.error("--user and --password go together")
    shop, mirror = start(args.port, args.mirror_port, args.user, args.password)
    print(f"shop   {shop.origin}", flush=True)
    print(f"mirror {mirror.origin}", flush=True)
    print(f"ROM_HUB_NETWORK_SWITCHFOIL={shop.origin},{mirror.origin}", flush=True)
    try:
        threading.Event().wait()
    except KeyboardInterrupt:
        stop(shop, mirror)


if __name__ == "__main__":
    main()
