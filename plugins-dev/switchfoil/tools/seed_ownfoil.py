"""Write the fixture shop's dummy files into a directory for Ownfoil to serve.

The files are the same generated bytes and made-up names that
`tools/fixture_shop.py` serves. They contain no game data. Without Switch
keys, Ownfoil identifies a file from its name alone and does not verify it.

    python3 tools/seed_ownfoil.py /tmp/games
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fixture_shop import FILES


def seed(directory: Path) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for file in FILES:
        path = directory / file.filename
        path.write_bytes(file.body)
        path.chmod(0o644)
        written.append(path)
    return written


def main(argv=None) -> None:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        raise SystemExit("usage: seed_ownfoil.py DIRECTORY")
    for path in seed(Path(args[0])):
        print(path)


if __name__ == "__main__":
    main()
