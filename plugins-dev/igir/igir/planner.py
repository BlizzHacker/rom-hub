"""Universal 1G1R command & RomM/Gaseous/Retrom cleanup script planner for Igir v5.8.0+.

Credits:
- Igir (`https://github.com/emmercm/igir/releases/tag/v5.8.0`) by Christian Emmer (GPL-3.0).
- RomM Igir cleanup workflow (`https://docs.romm.app/latest/ecosystem/igir/#the-cleanup-script`)
  and community integration concept by Ant#1695.
"""

from __future__ import annotations

import shlex

ALLOWED_COMMANDS = (
    "copy",
    "move",
    "link",
    "extract",
    "zip",
    "test",
    "dir2dat",
    "fixdat",
    "clean",
    "report",
)

BACKEND_OUTPUT_TOKENS = {
    "romm": "{romm}",
    "es-de": "{es}",
    "batocera": "{batocera}",
    "gaseous": "{romm}",
    "retrom": "{romm}",
    "mister": "{mister}",
    "pocket": "{pocket}",
}

DEFAULT_PROFILE: dict[str, object] = {
    "commands": ["copy", "extract", "test", "clean", "report"],
    "input_dirs": ["/downloads/rom-hub"],
    "output_dir": "/library/roms/{romm}",
    "dat_dirs": ["/config/dats"],
    "single_1g1r": True,
    "prefer_verified": True,
    "prefer_good": True,
    "prefer_regions": ["USA", "WORLD", "EUR", "JPN"],
    "prefer_languages": ["EN", "JA"],
    "no_demos": True,
    "no_prototypes": True,
    "no_betas": True,
    "dry_run": False,
}


def build_1g1r_command(cfg: dict[str, object] | None = None) -> list[str]:
    """Construct a safe, deterministic `igir` argv list for 1G1R sorting and verification."""
    merged = dict(DEFAULT_PROFILE)
    if isinstance(cfg, dict):
        merged.update({k: v for k, v in cfg.items() if v is not None})

    raw_cmds = merged.get("commands") or ["copy", "test", "report"]
    if isinstance(raw_cmds, str):
        raw_cmds = [raw_cmds]
    cmds = [str(c).strip() for c in raw_cmds if str(c).strip() in ALLOWED_COMMANDS]
    if not cmds:
        cmds = ["test", "report"]
    if merged.get("dry_run"):
        cmds = [c for c in cmds if c in ("test", "report")] or ["test", "report"]

    args = ["igir", *cmds]
    for dat_dir in merged.get("dat_dirs") or []:
        if str(dat_dir).strip():
            args.extend(["--dat", str(dat_dir).strip()])
    for in_dir in merged.get("input_dirs") or []:
        if str(in_dir).strip():
            args.extend(["--input", str(in_dir).strip()])

    out_dir = str(merged.get("output_dir") or "/library/roms/{romm}").strip()
    args.extend(["--output", out_dir])

    if merged.get("single_1g1r", True):
        args.append("--single")
    if merged.get("prefer_verified", True):
        args.append("--prefer-verified")
    if merged.get("prefer_good", True):
        args.append("--prefer-good")

    regions = [
        str(r).strip().upper()
        for r in (merged.get("prefer_regions") or [])
        if str(r).strip()
    ]
    if regions:
        args.extend(["--prefer-region", ",".join(regions)])

    langs = [
        str(lang).strip().upper()
        for lang in (merged.get("prefer_languages") or [])
        if str(lang).strip()
    ]
    if langs:
        args.extend(["--prefer-language", ",".join(langs)])

    if merged.get("no_demos", True):
        args.append("--no-demos")
    if merged.get("no_prototypes", True):
        args.append("--no-prototypes")
    if merged.get("no_betas", True):
        args.append("--no-betas")

    return args


def render_cleanup_script(
    *,
    backend: str = "romm",
    input_dir: str = "/downloads/rom-hub",
    library_roms_dir: str = "/library/roms",
    dat_dir: str = "/config/dats",
    prefer_regions: list[str] | None = None,
    prefer_languages: list[str] | None = None,
) -> str:
    """Render a standalone bash cleanup script modelled on RomM's Igir guide & Ant#1695's workflow."""
    token = BACKEND_OUTPUT_TOKENS.get(backend.strip().lower(), "{romm}")
    output_dir = f"{library_roms_dir.rstrip('/')}/{token}"
    cmd = build_1g1r_command(
        {
            "commands": ["copy", "extract", "test", "clean", "report"],
            "input_dirs": [input_dir],
            "output_dir": output_dir,
            "dat_dirs": [dat_dir],
            "single_1g1r": True,
            "prefer_verified": True,
            "prefer_good": True,
            "prefer_regions": prefer_regions or ["USA", "WORLD", "EUR", "JPN"],
            "prefer_languages": prefer_languages or ["EN", "JA"],
            "no_demos": True,
            "no_prototypes": True,
            "no_betas": True,
            "dry_run": False,
        }
    )
    quoted = " \\\n  ".join(shlex.quote(part) for part in cmd)
    return (
        "#!/usr/bin/env bash\n"
        "# Generated by ROM Hub / ROMarr Igir v5.8.0 1G1R plugin\n"
        "# Upstream tool: https://github.com/emmercm/igir/releases/tag/v5.8.0\n"
        "# Workflow ref:  https://docs.romm.app/latest/ecosystem/igir/#the-cleanup-script\n"
        "set -euo pipefail\n\n"
        f"{quoted}\n"
    )
